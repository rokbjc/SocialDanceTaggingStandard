"""Shared helpers for emitting checked-in C# id/value members from the YAML sources of truth
(CLAUDE.md coding guideline 2). Used by gen_ids.py. Matches the LF + auto-generated-header
discipline of the doc/vector generators. No third-party deps."""
from __future__ import annotations

import pathlib
import re


def pascal_case(s: str) -> str:
    """`rhythmic_feel` / `recording-quality-era` / `Songs DB` -> `RhythmicFeel` etc.
    Leading digit is prefixed with `_` so the result is a valid C# identifier."""
    parts = re.split(r"[^0-9A-Za-z]+", str(s))
    out = "".join(p[:1].upper() + p[1:] for p in parts if p)
    if not out:
        return "_"
    return ("_" + out) if out[0].isdigit() else out


def cs_string(s: str) -> str:
    """A C# double-quoted string literal (escapes backslash and quote)."""
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def xml_escape(s: str) -> str:
    """Escape DATA for an XML doc comment (the text inside <summary>, NOT the doc tags). Use on
    YAML-sourced values before composing them into a <summary> that also carries <c>/<see cref=…/> tags."""
    return str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def xmldoc(summary: str, indent: int = 4) -> str:
    """A single-line `/// <summary>…</summary>` doc comment at `indent` spaces. `summary` may contain
    XML doc tags (<c>, <see cref=…/>); escape any DATA in it with xml_escape first."""
    return f"{' ' * indent}/// <summary>{summary}</summary>\n"


def header(generator: str, source: str = "data/fields.yaml") -> str:
    """`// <auto-generated/>` header — Roslyn treats the file as generated, exempting it from
    CS1591/style warnings and `dotnet format`. The in-sync CI gate still diffs it. `source` names the
    YAML source of truth (guideline 2). `#nullable enable` is explicit because a `// <auto-generated/>`
    file gets a DISABLED nullable context by default, so any `?` annotation would trip CS8669."""
    return (
        "// <auto-generated/>\n"
        f"// Generated by scripts/{generator} from {source} — DO NOT EDIT.\n"
        f"// Regenerate: python scripts/{generator}  (CLAUDE.md coding guideline 2).\n"
        f"#pragma warning disable CS1591  // generated members; doc source of truth is {source}\n"
        "#nullable enable\n\n"
    )


def write_cs(path: pathlib.Path, body: str) -> None:
    """Write a generated .cs file with deterministic LF newlines (cross-platform)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8", newline="\n")
