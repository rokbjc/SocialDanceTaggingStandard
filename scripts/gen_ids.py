"""Generate strongly-typed C# id members from data/fields.yaml (CLAUDE.md coding guideline 2).

Emits (checked-in, LF, `// <auto-generated/>`):
  dotnet/src/SocialDanceTaggingStandard/Generated/FieldIds.g.cs              FieldId per field (core)
  dotnet/src/SocialDanceTaggingStandard/Generated/FieldCatalog.g.cs          runtime FieldMetadata per field (core)
  dotnet/src/SocialDanceTaggingStandard.Id3/Generated/Id3Frames.g.cs        Id3FrameId: standard ID3 frames (.Id3)
  dotnet/src/SocialDanceTaggingStandard.Id3/Generated/SdtsFrames.g.cs   Id3UserTextDescription: portable TXXX:SDTS_* (.Id3)
  dotnet/src/SocialDanceTaggingStandard.MediaMonkey/Generated/MmColumns.g.cs MM5 COMM/TXXX descriptions (.MediaMonkey)
  dotnet/src/SocialDanceTaggingStandard.MediaMonkey/Generated/MediaMonkeyMirrorMap.g.cs  the SDTS_* <-> Songs-DB_* key map

Reads only the committed data/fields.yaml (CI-safe). Routing per guideline 3:
portable standard frames + TXXX:SDTS_* -> .Id3; the legacy COMM:Songs-DB_* / TXXX:Quality columns -> .MediaMonkey.
"""
