# Per-field accessor shape for the generated SdtsFile members. Keyed by fields.yaml id.
# kind: "container" (delegate to ISdtsContainer), "timespan" (int ms -> TimeSpan?),
#       "enum" (closed enum + token map), "gates" (ConfirmationGates), "int" (int?).
# Fields absent here use the default: single enum -> string?, multi enum -> IReadOnlyList<string>.
# `member` renames just the C# property: a field id is singular (it names its dimension; cardinality is
# declared, not spelled), while a collection property reads plural — hence dance -> Dances, as with mood.
ACCESSOR_OVERRIDE = {
    "genre":  {"kind": "container", "member": "Genres", "type": "IReadOnlyList<string>"},
    "mood":   {"kind": "container", "member": "Moods",  "type": "IReadOnlyList<string>"},
    "bpm":    {"kind": "container", "member": "Bpm",    "type": "int?"},
    "rating": {"kind": "container", "member": "Rating", "type": "int?"},
    "playback_start": {"kind": "timespan"}, "playback_stop": {"kind": "timespan"},
    "intro_duration": {"kind": "timespan"}, "outro_duration": {"kind": "timespan"},
    "fade_in_duration": {"kind": "timespan"}, "fade_out_duration": {"kind": "timespan"},
    "ending_type":     {"kind": "enum", "enum": "EndingType",
                         "values": {"definitive": "Definitive", "fade": "Fade", "cold-stop": "ColdStop"}},
    "tempo_stability": {"kind": "enum", "enum": "TempoStability",
                         "values": {"stable": "Stable", "drift": "Drift", "rubato": "Rubato",
                                    "accelerando": "Accelerando", "tempo-change": "TempoChange"}},
    "meter":           {"kind": "enum", "enum": "Meter",
                         "values": {"2": "_2", "3": "_3", "4": "_4", "2/4": "_24", "3/4": "_34",
                                    "4/4": "_44", "6/8": "_68", "12/8": "_128"}},
    "confirmation_gates": {"kind": "gates"},
    "energy": {"kind": "int"}, "valence": {"kind": "int"}, "danceability": {"kind": "int"},
    "dance": {"member": "Dances"}, "routine": {"member": "Routines"},
    "instrument_led": {"member": "InstrumentsLed"}, "theme": {"member": "Themes"},
    "lyric_language": {"member": "LyricLanguages"},
    "regions": {"kind": "custom"},  # list-of-structs → hand-written typed accessor (SdtsRegions.cs)
}


def _load():
    with open(FIELDS_YAML, encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def emit_standard_version(data) -> str:
    """Generate SocialDanceTaggingStandard/Generated/SdtsStandard.g.cs: the single authoritative standard-version constant
    (data/fields.yaml `version`) plus the compare-on-load contract the `sdts_version` field describes in
    prose, so every consumer stamps and compares ONE value instead of minting its own version space."""
    version = data.get("version", "")
    body = [
        header("gen_ids.py"),
        "namespace SocialDanceTaggingStandard;\n\n",
        "/// <summary>The version of the Social-Dance Tagging Standard this library implements\n",
        "/// (data/fields.yaml <c>version</c>) — the one value every consumer stamps into the\n",
        "/// <c>sdts_version</c> field and compares on load.</summary>\n",
        "public static class SdtsStandard\n{\n",
        "    /// <summary>The current standard version string (semver, from data/fields.yaml <c>version</c>).\n",
        "    /// Stamp it into the <c>sdts_version</c> field on write; compare a file's stamped value on load.</summary>\n",
        f"    public const string Version = {cs_string(version)};\n\n",
        "    /// <summary>The compare-on-load contract: a file is current iff its stamped <c>sdts_version</c>\n",
        "    /// EQUALS <see cref=\"Version\"/> (ordinal). Any other value — including none — means the file was\n",
        "    /// normalised to a different standard version and the consumer SHOULD re-normalise / migrate it.\n",
        "    /// Exact-match, not semver ordering: the standard names one authoritative string and a file either\n",
        "    /// carries it or does not.</summary>\n",
        "    public static bool IsCurrent(string? stampedVersion) =>\n",
        "        string.Equals(stampedVersion, Version, StringComparison.Ordinal);\n",
        "}\n",
    ]
    write_cs(SRC / "SocialDanceTaggingStandard" / "Generated" / "SdtsStandard.g.cs", "".join(body))
    return version


def emit_field_ids(fields, std_fields) -> int:
    body = [
        header("gen_ids.py"),
        "using System.Collections.Frozen;\n\n",
        "namespace SocialDanceTaggingStandard;\n\n",
        '/// <summary>Canonical <see cref="FieldId"/> for every SDTS field (data/fields.yaml).</summary>\n',
        "public static class FieldIds\n{\n",
    ]
    for f in fields:
        name = pascal_case(f["id"])
        dn = xml_escape(f.get("display_name", f["id"]))
        sent = xml_escape(first_sentence(f.get("description", "")).rstrip())
        summary = f"The <c>{xml_escape(f['id'])}</c> field — {dn}." + (f" {sent}" if sent else "")
        body.append(xmldoc(summary))
        body.append(f"    public static readonly FieldId {name} = new({cs_string(f['id'])});\n")
    # Standard music-library metadata fields (data/fields.yaml `standard_fields`): context-independent
    # canonical ids for ubiquitous library fields (title/artist/…). NOT SDTS taxonomy fields (no spec/doc
    # surface); a FieldId is emitted so a consumer can key a taxonomy-agnostic field map without magic strings.
    if std_fields:
        body.append("\n")
        for f in std_fields:
            name = pascal_case(f["id"])
            dn = xml_escape(f.get("display_name", f["id"]))
            sent = xml_escape(first_sentence(f.get("description", "")).rstrip())
            summary = f"The <c>{xml_escape(f['id'])}</c> standard-library field — {dn}." + (f" {sent}" if sent else "")
            body.append(xmldoc(summary))
            body.append(f"    public static readonly FieldId {name} = new({cs_string(f['id'])});\n")
    # A by-value lookup so a raw field-id token (e.g. a confirmation-gate wire key) resolves to its
    # FieldId without re-spelling any literal. Ordinal: only the exact canonical id matches; legacy/alias
    # spellings are a caller/profile concern, resolved above this map.
    body.append(
        '\n    /// <summary>Every <see cref="FieldId"/> keyed by its raw <c>Value</c> (ordinal) — the canonical\n'
        "    /// wire-token lookup (e.g. confirmation-gate key resolution); legacy/alias spellings resolve above it.</summary>\n"
        "    public static readonly FrozenDictionary<string, FieldId> ByValue = new[]\n    {\n"
    )
    for f in fields + std_fields:
        body.append(f"        {pascal_case(f['id'])},\n")
    body.append("    }.ToFrozenDictionary(id => id.Value, StringComparer.Ordinal);\n")
    body.append("}\n")
    write_cs(SRC / "SocialDanceTaggingStandard" / "Generated" / "FieldIds.g.cs", "".join(body))
    return len(fields) + len(std_fields)


def emit_field_catalog(fields) -> int:
    """Generate SocialDanceTaggingStandard/Generated/FieldCatalog.g.cs: the RUNTIME field-metadata catalog (namespace
    SocialDanceTaggingStandard). Same source and shape as the FieldIds doc comments — display name, description, dj_use,
    group, layer, and the vocabulary dimension a field is backed by — but reachable at runtime through a
    FieldId, for a consumer that shows "what SDTS says a field is" without reading the YAML."""
    body = [
        header("gen_ids.py"),
        "using System.Collections.Frozen;\n\n",
        "namespace SocialDanceTaggingStandard;\n\n",
        '/// <summary>Runtime <see cref="FieldMetadata"/> for every SDTS field (data/fields.yaml), keyed by\n',
        '/// <see cref="FieldId"/> — the display name and prose the spec attaches to a field, without parsing YAML.</summary>\n',
        "public static class FieldCatalog\n{\n",
        '    /// <summary>Every field\'s <see cref="FieldMetadata"/>, in data/fields.yaml document order.</summary>\n',
        "    public static readonly FrozenDictionary<FieldId, FieldMetadata> All = new[]\n    {\n",
    ]
    for f in fields:
        name = pascal_case(f["id"])
        dj = f.get("dj_use")
        backing = backing_dimension(f["id"])
        body.append(
            f"        new FieldMetadata(FieldIds.{name}, "
            f"{cs_string(f.get('display_name', f['id']))}, "
            f"{cs_string(f.get('description', ''))}, "
            f"{cs_string(dj) if dj else 'null'}, "
            f"{cs_string(f.get('group', ''))}, "
            f"{cs_string(f.get('layer', ''))}, "
            f"{cs_string(backing) if backing else 'null'}),\n")
    body.append("    }.ToFrozenDictionary(m => m.Id);\n\n")
    body.append('    /// <summary>The <see cref="FieldMetadata"/> for <paramref name="field"/>, or null if it\n')
    body.append("    /// is not an SDTS field (e.g. a standard-library FieldId such as title/artist).</summary>\n")
    body.append("    public static FieldMetadata? For(FieldId field) => All.GetValueOrDefault(field);\n")
    body.append("}\n")
    write_cs(SRC / "SocialDanceTaggingStandard" / "Generated" / "FieldCatalog.g.cs", "".join(body))
    return len(fields)


def emit_id3_frames(fields, std_frames) -> int:
    seen: set[str] = set()
    rows: list[str] = []
    for f in fields:
        if f["id"] in ID3_STANDARD_FIELDS:
            tok = clean_frame(f.get("id3_current", "")).split()
            if tok and tok[0] != "n/a" and tok[0] not in seen:
                seen.add(tok[0])
                rows.append(tok[0])
    for sf in std_frames:
        tok = str(sf.get("frame", "")).split()
        if tok and tok[0] not in seen:
            seen.add(tok[0])
            rows.append(tok[0])
    body = [
        header("gen_ids.py"),
        "namespace SocialDanceTaggingStandard.Id3;\n\n",
        "/// <summary>Standard ID3v2 frame ids SDTS binds (data/fields.yaml). Portable per guideline 3 —\n",
        "/// MediaMonkey COMM columns live in SocialDanceTaggingStandard.MediaMonkey, never here.</summary>\n",
        "public static class Id3Frames\n{\n",
    ]
    frame_field = {}
    for f in fields:
        if f["id"] in ID3_STANDARD_FIELDS:
            tok = clean_frame(f.get("id3_current", "")).split()
            if tok and tok[0] != "n/a":
                frame_field.setdefault(tok[0], f)
    std_by_frame = {str(sf.get("frame", "")).split()[0]: sf for sf in std_frames if sf.get("frame")}
    for frame in rows:
        bound = frame_field.get(frame)
        if bound:
            summary = (f"ID3 standard frame <c>{frame}</c> — canonical home for the "
                       f'<see cref="SocialDanceTaggingStandard.FieldIds.{pascal_case(bound["id"])}"/> field '
                       f"({xml_escape(bound.get('display_name', bound['id']))}).")
        else:
            sf = std_by_frame.get(frame)
            concept = xml_escape(sf.get("field", "")) if sf else ""
            summary = f"ID3 standard frame <c>{frame}</c>" + (f" — {concept}." if concept else ".")
        body.append(xmldoc(summary))
        body.append(f"    public static readonly Id3FrameId {frame} = new({cs_string(frame)});\n")
    body.append("}\n")
    write_cs(SRC / "SocialDanceTaggingStandard.Id3" / "Generated" / "Id3Frames.g.cs", "".join(body))
    return len(rows)


def emit_sdt(fields) -> int:
    body = [
        header("gen_ids.py"),
        "namespace SocialDanceTaggingStandard.Id3;\n\n",
        "/// <summary>Portable SDTS TXXX:SDTS_* descriptions (data/fields.yaml `vorbis`) — the proposed\n",
        "/// format-neutral home for each field. Legacy MM columns are in .MediaMonkey.</summary>\n",
        "public static class SdtsFrames\n{\n",
    ]
    n = 0
    for f in fields:
        v = clean_frame(f.get("vorbis", ""))
        if v.startswith("SDTS_"):
            name = pascal_case(f["id"])
            summary = (f"<c>TXXX:{v}</c> — the portable SDTS home for the "
                       f'<see cref="SocialDanceTaggingStandard.FieldIds.{name}"/> field '
                       f"({xml_escape(f.get('display_name', f['id']))}).")
            body.append(xmldoc(summary))
            body.append(
                f"    public static readonly Id3UserTextDescription {name} = new({cs_string(v)});\n"
            )
            n += 1
    body.append("}\n")
    write_cs(SRC / "SocialDanceTaggingStandard.Id3" / "Generated" / "SdtsFrames.g.cs", "".join(body))
    return n


def emit_mm_columns(fields) -> int:
    comm: list[tuple[str, str, str]] = []
    txxx: list[tuple[str, str, str]] = []
    for f in fields:
        cur = clean_frame(f.get("id3_current", ""))
        dn = f.get("display_name", f["id"])
        if cur.startswith("COMM:Songs-DB_") or cur.startswith("COMM:MusicMatch"):
            comm.append((pascal_case(f["id"]), cur[len("COMM:"):], dn))
        elif cur.startswith("TXXX:") and not cur.startswith("TXXX:SDTS_"):
            txxx.append((pascal_case(f["id"]), cur[len("TXXX:"):], dn))
    body = [
        header("gen_ids.py"),
        "using SocialDanceTaggingStandard.Id3;\n\n",
        "namespace SocialDanceTaggingStandard.MediaMonkey;\n\n",
        "/// <summary>MediaMonkey 5 legacy frame descriptions (data/fields.yaml id3_current) — the MM5-specific\n",
        "/// COMM:Songs-DB_* / TXXX:Quality columns that guideline 3 keeps OUT of the portable .Id3 binding.</summary>\n",
        "public static class MmColumns\n{\n",
    ]
    # The property is named after the COLUMN it IS (Songs-DB_Custom3 → SongsDBCustom3), not the field it
    # currently holds — this is a column registry; the field↔column assignment is the mapping
    # (MediaMonkeyMirrorMap + data/fields.yaml). The field stays in the doc + the <see cref>.
    for name, desc, dn in comm:
        summary = (f"MM5 legacy column <c>COMM:{desc}</c> — holds the "
                   f'<see cref="SocialDanceTaggingStandard.FieldIds.{name}"/> field '
                   f"({xml_escape(dn)}) on existing files.")
        body.append(xmldoc(summary))
        body.append(f"    public static readonly Id3CommentDescription {pascal_case(desc)} = new({cs_string(desc)});\n")
    for name, desc, dn in txxx:
        summary = (f"MM5 native <c>TXXX:{desc}</c> — holds the "
                   f'<see cref="SocialDanceTaggingStandard.FieldIds.{name}"/> field ({xml_escape(dn)}).')
        body.append(xmldoc(summary))
        body.append(f"    public static readonly Id3UserTextDescription {pascal_case(desc)} = new({cs_string(desc)});\n")
    body.append("}\n")
    write_cs(SRC / "SocialDanceTaggingStandard.MediaMonkey" / "Generated" / "MmColumns.g.cs", "".join(body))
    return len(comm) + len(txxx)


def emit_mm_mirror_map(fields) -> int:
    """The canonical SDTS_* (TXXX) <-> MM5 COMM:Songs-DB_* key map (MediaMonkeyFrames.Map), built from the
    typed FieldIds/Sdts/MmColumns constants for every field flagged `mm5_mirror: true`. The only hand-decided
    datum is the subset itself, and it lives in data/fields.yaml — never the frame literals (guidelines 1 + 2)."""
    rows: list[str] = []
    for f in fields:
        if not f.get("mm5_mirror"):
            continue
        vorbis = clean_frame(f.get("vorbis", ""))
        current = clean_frame(f.get("id3_current", ""))
        if not vorbis.startswith("SDTS_") or not current.startswith("COMM:Songs-DB_"):
            raise SystemExit(
                f"mm5_mirror field '{f['id']}' needs an SDTS_* vorbis key and a COMM:Songs-DB_* id3_current "
                f"slot (got vorbis={vorbis!r}, id3_current={current!r})")
        # (field-id member name for FieldIds/Sdts, column member name for MmColumns)
        rows.append((pascal_case(f["id"]), pascal_case(current[len("COMM:"):])))
    body = [
        header("gen_ids.py"),
        "using SocialDanceTaggingStandard;\n",
        "using SocialDanceTaggingStandard.Id3;\n",
        "using SocialDanceTaggingStandard.Sync;\n\n",
        "namespace SocialDanceTaggingStandard.MediaMonkey;\n\n",
        "/// <summary>The canonical SDTS_* (TXXX) ⇄ MediaMonkey COMM:Songs-DB_* key map for the fields flagged\n",
        "/// `mm5_mirror: true` in data/fields.yaml. Every row is built from the typed FieldId / SdtsFrames / MmColumns\n",
        "/// constants, so a frame id is never re-spelled here (CLAUDE.md coding guidelines 1 + 2).</summary>\n",
        "public static class MediaMonkeyMirrorMap\n{\n",
        "    /// <summary>The mm5_mirror field set, in data/fields.yaml document order.</summary>\n",
        "    public static readonly IReadOnlyList<FieldMirror> Map =\n    [\n",
    ]
    for name, col in rows:
        body.append(
            f"        new FieldMirror(FieldIds.{name}, new TagKey(SdtsFrames.{name}.Value), new TagKey(MmColumns.{col}.Value)),\n")
    body.append("    ];\n}\n")
    write_cs(SRC / "SocialDanceTaggingStandard.MediaMonkey" / "Generated" / "MediaMonkeyMirrorMap.g.cs", "".join(body))
    return len(rows)


def emit_field_enums(fields) -> int:
    """Generate SocialDanceTaggingStandard/Generated/SdtsFieldEnums.g.cs (namespace SocialDanceTaggingStandard): each closed SDTS field enum
    (EndingType/TempoStability/Meter) with a ToToken()/Parse() round-trip to its data/fields.yaml token.
    Enums live in core because they are standard, format-neutral (a future Vorbis binding reuses them);
    mirrors the shape of emit_vocab_enums in gen_vocab_docs.py. Members + tokens come from each override's
    `values` map (member name -> wire token, reversed for Parse)."""
    enums = [(f, ACCESSOR_OVERRIDE[f["id"]]) for f in fields
             if ACCESSOR_OVERRIDE.get(f["id"], {}).get("kind") == "enum"]
    body = [
        header("gen_ids.py"),
        "namespace SocialDanceTaggingStandard;\n\n",
    ]
    for f, ov in enums:
        enum = ov["enum"]
        # values map is {wire token: C# member}; emit members in insertion (fields.yaml) order.
        members = [(member, tok) for tok, member in ov["values"].items()]
        dn = xml_escape(f.get("display_name", f["id"]))
        body.append(f"/// <summary>The closed <c>{enum}</c> SDTS field ({dn}); see {enum}Tokens for the\n")
        body.append("/// data/fields.yaml token round-trip. Its own type so field values never mix (CLAUDE.md guideline 1).</summary>\n")
        body.append(f"public enum {enum}\n{{\n")
        body += [f"    /// <summary><c>{xml_escape(tok)}</c></summary>\n    {m},\n" for m, tok in members]
        body.append("}\n\n")
        body.append(f"/// <summary>data/fields.yaml token round-trip for <see cref=\"{enum}\"/>.</summary>\n")
        body.append(f"public static class {enum}Tokens\n{{\n")
        body.append(f"    /// <summary>The canonical data/fields.yaml token for an <see cref=\"{enum}\"/> value.</summary>\n")
        body.append(f"    public static string ToToken(this {enum} value) => value switch\n    {{\n")
        body += [f"        {enum}.{m} => {cs_string(tok)},\n" for m, tok in members]
        body.append("        _ => throw new System.ArgumentOutOfRangeException(nameof(value)),\n    };\n\n")
        body.append(f"    /// <summary>Parse a data/fields.yaml token to its <see cref=\"{enum}\"/>, or null if unknown.</summary>\n")
        body.append(f"    public static {enum}? Parse(string? token) => token switch\n    {{\n")
        body += [f"        {cs_string(tok)} => {enum}.{m},\n" for m, tok in members]
        body.append("        _ => null,\n    };\n}\n\n")
    write_cs(SRC / "SocialDanceTaggingStandard" / "Generated" / "SdtsFieldEnums.g.cs", "".join(body))
    return len(enums)


def emit_record_accessors(fields) -> int:
    """Generate SocialDanceTaggingStandard.Id3/Generated/SdtsRecordAccessors.g.cs: the typed per-field accessors of the
    container-less SdtsRecord base (a `public partial class SdtsRecord`). Every SDTS_-backed field
    (multi / scalar / int / timespan / enum / gates); container-backed genre/mood/bpm/rating live on
    SdtsFile. Also emits the FieldFrames map (FieldId -> Id3UserTextDescription) for every SDTS_-backed
    field."""
    body = [
        header("gen_ids.py"),
        "using System.Collections.Frozen;\n",
        "using SocialDanceTaggingStandard;\n\n",
        "namespace SocialDanceTaggingStandard.Id3;\n\n",
        "/// <summary>Generated typed per-field accessors for the container-less <see cref=\"SdtsRecord\"/>\n",
        "/// base (data/fields.yaml). SDTS_* fields read/write the TXXX region via the hand-written primitives;\n",
        "/// container-backed genre/mood/bpm/rating live on <see cref=\"SdtsFile\"/>.</summary>\n",
        "public partial class SdtsRecord\n{\n",
    ]
    frame_rows: list[str] = []
    for f in fields:
        name = pascal_case(f["id"])
        dn = xml_escape(f.get("display_name", f["id"]))
        ov = ACCESSOR_OVERRIDE.get(f["id"]) or {}
        vorbis = clean_frame(f.get("vorbis", ""))
        kind = ov.get("kind")
        # The FieldId / SdtsFrames constants keep the field-id spelling; only the property may be renamed.
        member = ov.get("member", name)
        if kind == "container":
            continue  # container-backed → SdtsFile (emit_file_accessors)
        if kind == "timespan":
            body.append(xmldoc(f"{dn} — millisecond scalar surfaced as a <see cref=\"System.TimeSpan\"/>."))
            body.append(
                f"    public System.TimeSpan? {member} {{ get => GetMs(SdtsFrames.{name}); "
                f"set => SetMs(SdtsFrames.{name}, value); }}\n")
        elif kind == "enum":
            enum = ov["enum"]
            body.append(xmldoc(f"{dn} — closed <see cref=\"SocialDanceTaggingStandard.{enum}\"/> field."))
            body.append(
                f"    public SocialDanceTaggingStandard.{enum}? {member} {{ "
                f"get => SocialDanceTaggingStandard.{enum}Tokens.Parse(GetScalar(SdtsFrames.{name})); "
                f"set => SetScalar(SdtsFrames.{name}, value?.ToToken()); }}\n")
        elif kind == "gates":
            body.append(xmldoc(f"{dn} — the confirmation-gate ledger (keyed by field id; see SocialDanceTaggingStandard.Gates)."))
            body.append(
                f"    public SocialDanceTaggingStandard.Gates.ConfirmationGates Gates {{ get => GetGates(SdtsFrames.{name}); "
                f"set => SetGates(SdtsFrames.{name}, value); }}\n")
        elif kind == "int":
            body.append(xmldoc(f"{dn} — integer scalar."))
            body.append(
                f"    public int? {member} {{ get => GetInt(SdtsFrames.{name}); "
                f"set => SetInt(SdtsFrames.{name}, value); }}\n")
        elif kind != "custom" and vorbis.startswith("SDTS_"):
            if f.get("cardinality") == "multi":
                body.append(xmldoc(f"{dn} — multi-value SDTS_* field (\"; \"-joined)."))
                body.append(
                    f"    public IReadOnlyList<string> {member} {{ get => GetMulti(SdtsFrames.{name}); "
                    f"set => SetMulti(SdtsFrames.{name}, value); }}\n")
            else:
                body.append(xmldoc(f"{dn} — single-value SDTS_* string field."))
                body.append(
                    f"    public string? {member} {{ get => GetScalar(SdtsFrames.{name}); "
                    f"set => SetScalar(SdtsFrames.{name}, value); }}\n")
        # FieldFrames row for every SDTS_-backed field (container fields live on the container, not here).
        if vorbis.startswith("SDTS_"):
            frame_rows.append(f"        [FieldIds.{name}] = SdtsFrames.{name},")
    body.append("\n")
    body.append("    /// <summary>SDTS_*-backed fields, mapping each <see cref=\"FieldId\"/> to its TXXX description.</summary>\n")
    body.append("    private static readonly FrozenDictionary<FieldId, Id3UserTextDescription> FieldFrames =\n")
    body.append("        new Dictionary<FieldId, Id3UserTextDescription>\n        {\n")
    body.append("\n".join(frame_rows))
    body.append("\n        }.ToFrozenDictionary();\n")
    body.append("}\n")
    write_cs(SRC / "SocialDanceTaggingStandard.Id3" / "Generated" / "SdtsRecordAccessors.g.cs", "".join(body))
    return len(frame_rows)


def emit_file_accessors(fields) -> int:
    """Generate SocialDanceTaggingStandard.Id3/Generated/SdtsFileAccessors.g.cs: the container-backed accessors of the
    file-backed SdtsFile gateway (a `public partial class SdtsFile`) — genre/mood/bpm/rating, each
    delegating to the non-null ISdtsContainer. Every SDTS_-backed accessor lives on SdtsRecord."""
    body = [
        header("gen_ids.py"),
        "namespace SocialDanceTaggingStandard.Id3;\n\n",
        "/// <summary>Generated container-backed accessors for the file-backed <see cref=\"SdtsFile\"/> gateway\n",
        "/// (data/fields.yaml): genre/mood/bpm/rating delegate to the non-null <see cref=\"ISdtsContainer\"/>.</summary>\n",
        "public partial class SdtsFile\n{\n",
    ]
    n = 0
    for f in fields:
        ov = ACCESSOR_OVERRIDE.get(f["id"])
        if not ov or ov.get("kind") != "container":
            continue
        name = pascal_case(f["id"])
        dn = xml_escape(f.get("display_name", f["id"]))
        summary = (f"{dn} — delegates to the standard-frame container "
                   f'(<see cref="ISdtsContainer.{ov["member"]}"/>).')
        body.append(xmldoc(summary))
        body.append(
            f"    public {ov['type']} {name} {{ get => Container.{ov['member']}; "
            f"set => Container.{ov['member']} = value; }}\n")
        n += 1
    body.append("}\n")
    write_cs(SRC / "SocialDanceTaggingStandard.Id3" / "Generated" / "SdtsFileAccessors.g.cs", "".join(body))
    return n


